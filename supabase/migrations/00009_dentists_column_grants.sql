-- =============================================================================
-- Tishim — Migration 00009: колоночные права на dentists
--
-- Миграция 00005 выдала authenticated UPDATE на всю таблицу, а политика
-- «dentists: own update» ограничивает только строку — но не колонки. В итоге
-- врач мог одним PATCH к REST API выставить себе is_featured и занять карточку
-- на лендинге, а вместе с ней получить доступ ко всем mapping_requests: их
-- читает флагман (политика «mapping_requests: staff read»), то есть имена и
-- телефоны всех оставивших заявку. Проверено на живой базе: пока флагман уже
-- назначен, попытку отбивает уникальный индекс dentists_single_featured_key
-- (409), но стоит флагману освободиться — например, сразу после развёртывания —
-- и назначение проходит. Тем же способом врач мог нарисовать себе rating.
--
-- Колоночный revoke поверх табличного гранта в PostgreSQL бесполезен: табличное
-- право перекрывает колоночное. Поэтому снимаем UPDATE с таблицы целиком и
-- возвращаем поимённо только те колонки, которые правит интерфейс.
--
-- Админский путь не затронут: set_featured_dentist — security definer,
-- выполняется от владельца и прав вызывающего не спрашивает. INSERT и DELETE
-- не трогаем: их и так держит RLS — политики на insert для dentists нет вовсе,
-- а delete разрешён только админу.
-- =============================================================================

revoke update on public.dentists from anon, authenticated;

-- Что пишет врач в своём профиле (DentistProfileSetup) и админ при назначении
-- клиники (DentistsPanel). is_featured и rating сюда намеренно не входят.
grant update (
  specialization,
  license_number,
  clinic_id,
  bio,
  photo_url,
  experience_years
) on public.dentists to authenticated;
